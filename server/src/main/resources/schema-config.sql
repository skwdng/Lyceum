-- ============================================================================
-- 后台参数（feature-admin-config）：两张表
--
-- 设计：`参数管理-设计方案.md` §2
--
-- 为什么单独一个文件：既有 schema 一律不动，新表只进这里；
-- application.yml 的 schema-locations 把它排在**最后**（它不引用任何别的表）。
--
-- 只存"被后台改过的值"：
--   · 库里没有这一行  -> 用 ConfigKey 枚举里的默认值（= 改造前的 yml / 常量值）
--   · 所以上线即兼容，逐项灰度：改哪个键，哪个键的热更才真正开始
--   · 回滚到默认值 = 删掉那一行（见 ConfigService#rollback）
-- ============================================================================

-- 当前值（k 是主键：一个键只有一行，正是"先 update 再 insert"能成立的前提）
--   k          alert.report.threshold 这样的键名，与 ConfigKey 枚举一一对应
--   v          一律按字符串存（类型由枚举声明，读到再转）—— 好处是布尔/整数/字符串共用一张表
--   type       BOOL / INT / STRING（写的时候记一份，方便直接看库排查）
--   updated_by 最后改的人（管理员账号；启动期/脚本为空）
create table if not exists sy_config (
  k          varchar(64)  primary key,
  v          varchar(500) not null,
  type       varchar(8)   not null,
  updated_by varchar(64),
  updated_at timestamp    not null default current_timestamp
);

-- 修改历史（参数页的"历史 + 一键回滚"就是读它）
--   old_v  改之前的值；**null 表示改之前库里没有这一行**（回滚 = 删掉那一行，回到默认值）
--   new_v  改之后的值（非空）
create table if not exists sy_config_log (
  id         bigint generated by default as identity primary key,
  k          varchar(64)  not null,
  old_v      varchar(500),
  new_v      varchar(500) not null,
  operator   varchar(64),
  created_at timestamp    not null default current_timestamp
);

-- 某个键的历史倒序（参数页展开某一行时按 k 查）
create index if not exists ix_config_log_k on sy_config_log(k, created_at);
