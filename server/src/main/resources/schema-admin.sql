-- 举报 + 管理员后台（com.siyige.admin）：三张新表 + 一条种子管理员
--
-- 只新建表，**不动任何既有表结构**：
--   · schema.sql / schema-community.sql / schema-auth.sql 一行不改
--   · 唯一复用的是 sy_user.status（schema-auth.sql 里早已加好的列），本期启用为「全站封禁」开关
--
-- 两种处罚，互不干扰：
--   · sy_community_ban —— 社区禁言：有期限（1/3/7 天），到期自动解除
--   · sy_user.status   —— 全站封禁：立即生效，需手动解封
--
-- 顺序要求：application.yml 的 schema-locations 里本文件必须排在**最后**
-- （语义上依赖 schema.sql 已建好 sy_user）。
--
-- 种子管理员：admin / admin123
--   ⚠️ 仅供本地演示，生产必须改密（方案 §8 R1）。
--   哈希是 Argon2id 常量（参数 m=19456,t=2,p=1，与 com.siyige.auth.PasswordConfig 一致），
--   运行时无法生成，所以写死在这里；改密码时必须同步改这一行。
--   用 merge ... key(account) 保证重复执行不会插两条（本地 H2 是内存库，重启即清空）。
-- ============================================================================

-- 管理员（独立账号体系，与 sy_user 完全无关）
create table if not exists sy_admin (
  id            bigint generated by default as identity primary key,
  account       varchar(64)  not null,
  password_hash varchar(255) not null,
  status        tinyint      not null default 1,
  created_at    timestamp    not null default current_timestamp
);

create unique index if not exists ux_admin_account on sy_admin(account);

-- 举报
--   target_type : POST | COMMENT（不做「举报用户」）
--   reason      : SPAM | ABUSE | ILLEGAL | OTHER
--   status      : PENDING | ACCEPTED | REJECTED
--   action      : IGNORE | DELETE | BAN | DELETE_AND_BAN
--   detail      : 举报人填的补充说明，**落库前已过 SensitiveWordMasker 打码**
create table if not exists sy_report (
  id          bigint generated by default as identity primary key,
  target_type varchar(8)   not null,
  target_id   bigint       not null,
  reporter_id varchar(32)  not null,
  reason      varchar(32)  not null,
  detail      varchar(500) null,
  status      varchar(16)  not null default 'PENDING',
  handled_by  bigint       null,
  handled_at  timestamp    null,
  action      varchar(16)  null,
  created_at  timestamp    not null default current_timestamp
);

-- 同一个人对同一个目标只能举报一次（重复举报靠它兜底 -> 409 ALREADY_REPORTED）
create unique index if not exists ux_report_once on sy_report(target_type, target_id, reporter_id);
create index        if not exists ix_report_status on sy_report(status, created_at);
create index        if not exists ix_report_target on sy_report(target_type, target_id);

-- 社区禁言（有期限，到期自动解除；与全站封禁 sy_user.status 互不干扰）
create table if not exists sy_community_ban (
  id         bigint generated by default as identity primary key,
  user_id    varchar(32)  not null,
  banned_by  bigint       not null,
  reason     varchar(200) null,
  until      timestamp    not null,
  created_at timestamp    not null default current_timestamp
);

create index if not exists ix_ban_user on sy_community_ban(user_id, until);

