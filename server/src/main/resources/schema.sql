create table if not exists sy_user (
  id         varchar(32) primary key,
  name       varchar(64),
  created_at timestamp default current_timestamp
);

create table if not exists sy_topic (
  id           varchar(32) primary key,
  title        varchar(200),
  cat          varchar(32),
  diff         varchar(16),
  source       varchar(16) default 'official',   -- official | custom
  plays        int default 0,
  mod_status   varchar(16) default 'PASS',       -- PASS | REJECT | NEED_EDIT | pending
  mod_reason   varchar(300),
  mod_at       timestamp,
  title_hash   varchar(64)
);

create table if not exists sy_match (
  id           varchar(40) primary key,
  user_id      varchar(32),
  topic_id     varchar(32),
  topic_title  varchar(200),
  mode         varchar(16),        -- FULL | SPRINT | DRILL
  my_seats     varchar(40),        -- 例如 "A1,A2"
  step         int default 0,
  status       varchar(16),        -- RUNNING | REVIEW | FINISHED | FAILED
  deadline_at  timestamp,
  started_at   timestamp default current_timestamp,
  finished_at  timestamp,
  total_score  int
);

create table if not exists sy_turn (
  id         bigint generated by default as identity primary key,
  match_id   varchar(40),
  step       int,
  seat       varchar(4),
  seg        varchar(16),
  content    varchar(4000),
  status     varchar(16),          -- OK | TIMEOUT
  input_type varchar(16),          -- kb | voice | skipped | timeout
  created_at timestamp default current_timestamp
);
create index if not exists ix_turn on sy_turn(match_id, step);

create table if not exists sy_audit (
  id          bigint generated by default as identity primary key,
  title       varchar(200),
  title_hash  varchar(64),
  result      varchar(16),
  reason      varchar(300),
  suggestions varchar(600),
  cached      boolean default false,
  created_at  timestamp default current_timestamp
);

create table if not exists sy_record (
  id          bigint generated by default as identity primary key,
  user_id     varchar(32),
  match_id    varchar(40),
  topic_title varchar(200),
  seats       varchar(40),
  total       int,
  turns       int,
  created_at  timestamp default current_timestamp
);

create table if not exists sy_diag (
  user_id    varchar(32) primary key,
  dims_json  varchar(600),
  flaws_json varchar(600),
  streak     int default 0,
  updated_at timestamp default current_timestamp
);

create table if not exists sy_event (
  id         bigint generated by default as identity primary key,
  match_id   varchar(40),
  seq        int,
  type       varchar(32),
  payload    varchar(4000),
  created_at timestamp default current_timestamp
);

create table if not exists sy_room (
  code         varchar(16) primary key,
  topic_id     varchar(32),
  topic_title  varchar(200),
  visibility   varchar(16) default 'public',
  host_user    varchar(32),
  status       varchar(16) default 'LOBBY',
  match_id     varchar(40),
  created_at   timestamp default current_timestamp
);

create table if not exists sy_seat (
  room_code  varchar(16),
  seat_key   varchar(4),
  side       varchar(2),
  role       varchar(8),
  occupant   varchar(8) default 'EMPTY',
  user_id    varchar(32),
  user_name  varchar(64),
  ready      boolean default false,
  primary key (room_code, seat_key)
);

create table if not exists sy_evidence (
  id       varchar(32) primary key,
  topic_id varchar(32),
  side     varchar(2),          -- A 正方 / B 反方 / C 双方可用
  claim    varchar(300),        -- 可核查的事实陈述或口径
  source   varchar(200),        -- 出处
  pub_year int,          -- YEAR 是 H2 保留字，不能直接做列名
  verified boolean default false,
  tags     varchar(100)
);
create index if not exists ix_ev_topic on sy_evidence(topic_id);
