-- 辩场（辩论短视频模块）
create table if not exists sy_video (
  id           bigint generated by default as identity primary key,
  user_id      varchar(32) not null,   -- 不强加外键：辩论侧的用户可能是匿名 id
  title        varchar(120) not null,
  description  varchar(1000),
  url          varchar(500) not null,
  poster       varchar(500),
  topic        varchar(80),
  segment      varchar(16),
  side         varchar(8),
  duration_sec int default 0,
  likes        int default 0,
  views        int default 0,
  comments     int default 0,
  audit_status varchar(16) default 'PENDING',
  audit_note   varchar(200),
  status       varchar(16) default 'ONLINE',
  created_at   timestamp default current_timestamp
);
create index if not exists ix_video_feed on sy_video(audit_status, status, id desc);
create index if not exists ix_video_user on sy_video(user_id, id desc);

create table if not exists sy_video_comment (
  id         bigint generated by default as identity primary key,
  video_id   bigint not null,
  user_id    varchar(32) not null,
  content    varchar(500) not null,
  created_at timestamp default current_timestamp
);
create index if not exists ix_vcomment_video on sy_video_comment(video_id, id desc);

create table if not exists sy_video_like (
  id         bigint generated by default as identity primary key,
  video_id   bigint not null,
  user_id    varchar(32) not null
);
create unique index if not exists ux_vlike on sy_video_like(video_id, user_id);

-- 电子审核留痕：机器初审 + 人工复核 + 一键恢复，全部可追溯
create table if not exists sy_video_audit (
  id          bigint generated by default as identity primary key,
  video_id    bigint not null,
  stage       varchar(16) not null,
  result      varchar(16) not null,
  reason      varchar(300),
  operator    varchar(64),
  snapshot    varchar(2000),
  prev_status varchar(16),
  restored    boolean default false,
  created_at  timestamp default current_timestamp
);
create index if not exists ix_vaudit_video on sy_video_audit(video_id, id desc);
