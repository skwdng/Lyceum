-- ============================================================================
-- 安全与审计：改密码（旧令牌失效）+ 处理记录 + 一键恢复
--
-- 只做增量：ALTER 三个列 + 建一张审计表。
-- **不改任何既有脚本**（schema.sql / schema-community.sql / schema-auth.sql / schema-admin.sql 一行不动）。
--
-- 顺序要求：application.yml 的 schema-locations 里本文件必须排在**最后**
-- （依赖 sy_user / sy_admin / sy_community_ban 都已建好）。
--
-- ── pwd_changed_at ─────────────────────────────────────────────────────────
--   改密时间。JwtAuthFilter / AdminAuthFilter 拿 JWT 的 iat 与它比较：
--   早于它签发的令牌一律 401 TOKEN_STALE —— 改完密码，该账号**所有旧令牌立刻失效**。
--   ⚠️ JWT 的 iat 只到**秒**，本列是毫秒级 timestamp，比较时必须把本列**截断到秒**，
--      否则"改密后同一秒签发的新令牌"会被自己判成过期（用户改完密码立刻被踢）。
--      实现见 com.siyige.auth.AuthState#isTokenStale。
--
-- ── sy_community_ban.report_id ────────────────────────────────────────────
--   这次禁言是被哪一条举报触发的（归属标记 + 审计追溯用）。
--   ⚠️ 一键恢复**不碰禁言**：恢复只把被删内容的 status 由 2 改回 1；
--      禁言要解除请到「用户管理」页手动解禁（决策 E / 用户确认）。
--
-- ── sy_audit_log ──────────────────────────────────────────────────────────
--   只记两种动作：REPORT_RESOLVE（管理员处理举报）/ RESTORE（撤销那次处理）。
--   **不记**：管理员登录、登录失败、改密码、用户侧任何动作。
--   这里**绝不能出现密码、令牌或任何凭据**：detail 只写人可读的业务描述。
-- ============================================================================

alter table sy_user  add column if not exists pwd_changed_at timestamp;
alter table sy_admin add column if not exists pwd_changed_at timestamp;
alter table sy_community_ban add column if not exists report_id bigint;

create table if not exists sy_audit_log (
  id          bigint generated by default as identity primary key,
  report_id   bigint       not null,          -- 关联 sy_report.id
  admin_id    bigint       not null,          -- 操作人 sy_admin.id
  admin_name  varchar(64),                    -- 冗余账号，改名不影响历史
  action      varchar(24)  not null,          -- REPORT_RESOLVE | RESTORE
  verdict     varchar(24),                    -- IGNORE | DELETE | BAN | DELETE_AND_BAN（仅 REPORT_RESOLVE）
  target_type varchar(8),                     -- POST | COMMENT
  target_id   bigint,
  detail      varchar(500),                   -- 人读描述，禁止出现凭据
  undo_at     timestamp    null,              -- 被撤销的时间（null = 仍生效）
  undo_by     bigint       null,              -- 撤销人 sy_admin.id
  ip          varchar(64),
  created_at  timestamp    not null default current_timestamp
);

create index if not exists ix_audit_report on sy_audit_log(report_id, created_at);
create index if not exists ix_audit_time   on sy_audit_log(created_at);

-- ── 内容管理台：直接处置也要能留痕 ──────────────────────────────────────────
--   source        来源：REPORT（举报处理，默认）/ MANUAL（管理员从内容管理直接处置）
--   target_owner  内容作者的用户 id（用户浮窗按人查违规历史；禁言这类"目标是用户"的记录也填它）
-- MANUAL 时 report_id 写 0（AuditLogRepo.MANUAL_REPORT_ID），
-- RestoreService 见到 report_id <= 0 会跳过"把关联举报改回 REOPENED"，其余逻辑不变。
alter table sy_audit_log add column if not exists source       varchar(16) default 'REPORT';
alter table sy_audit_log add column if not exists target_owner varchar(32);
