create table if not exists sy_post (
  id              bigint generated by default as identity primary key,
  author_id       varchar(32)  not null,              -- 作者 user id；只展示昵称（R-COM-03）
  type            varchar(8)   not null,              -- CHAT | GUIDE | HELP
  title           varchar(120) not null,
  body            clob         not null,              -- Markdown（R-COM-06 仅外链图片）
  excerpt         varchar(220) not null,              -- R-COM-05 服务端截取 <=200
  topic_id        varchar(32)  null,                  -- 关联 sy_topic.id，可空
  comment_count   int          not null default 0,    -- R-COM-22 含楼中楼
  like_count      int          not null default 0,
  view_count      int          not null default 0,
  hot_score       double       not null default 0,    -- R-COM-13
  last_comment_at timestamp    null,
  status          tinyint      not null default 1,    -- 1 正常 / 2 软删除
  created_at      timestamp    not null default current_timestamp,
  updated_at      timestamp    null
);
create index if not exists ix_post_new      on sy_post(status, created_at);
create index if not exists ix_post_comments on sy_post(status, comment_count);
create index if not exists ix_post_likes    on sy_post(status, like_count);
create index if not exists ix_post_hot      on sy_post(status, hot_score);
create index if not exists ix_post_type     on sy_post(status, type, created_at);
create index if not exists ix_post_topic    on sy_post(topic_id, status, created_at);
create index if not exists ix_post_author   on sy_post(author_id, created_at);

create table if not exists sy_post_comment (
  id                      bigint generated by default as identity primary key,
  post_id                 bigint        not null,
  user_id                 varchar(32)   not null,
  root_id                 bigint        null,          -- 楼中楼所属楼；楼为 NULL（R-COM-17/18）
  reply_object_type       varchar(8)    not null default 'POST',  -- POST | COMMENT
  reply_object_comment_id bigint        null,
  reply_object_user_id    varchar(32)   null,
  body                    varchar(1000) not null,
  like_count              int           not null default 0,
  status                  tinyint       not null default 1,
  created_at              timestamp     not null default current_timestamp
);
create index if not exists ix_cmt_post on sy_post_comment(post_id, status, root_id, created_at);
create index if not exists ix_cmt_root on sy_post_comment(root_id, status, created_at);
create index if not exists ix_cmt_user on sy_post_comment(user_id, created_at);

create table if not exists sy_community_like (
  user_id     varchar(32) not null,
  target_type varchar(8)  not null,                    -- POST | COMMENT
  target_id   bigint      not null,
  created_at  timestamp   not null default current_timestamp,
  primary key (user_id, target_type, target_id)        -- 主键保证幂等（R-COM-27）
);
create index if not exists ix_like_target on sy_community_like(target_type, target_id);
