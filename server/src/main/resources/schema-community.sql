-- 社区模块表（由社区负责人维护，其他人不要改这个文件）
create table if not exists sy_post (
  id         bigint generated by default as identity primary key,
  user_id    varchar(32),
  user_name  varchar(64),
  title      varchar(120),
  content    varchar(4000),
  topic_id   varchar(32),
  likes      int default 0,
  created_at timestamp default current_timestamp
);

create table if not exists sy_comment (
  id         bigint generated by default as identity primary key,
  post_id    bigint,
  user_id    varchar(32),
  user_name  varchar(64),
  content    varchar(1000),
  created_at timestamp default current_timestamp
);
create index if not exists ix_comment_post on sy_comment(post_id);
