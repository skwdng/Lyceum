-- =====================================================================
-- 社区通知（2026-11-04 新增，V1）
-- 归属：com/siyige/community/NotificationService + NotificationRepo
--
-- 为什么单开一个文件：协作规范 §6 规定**不许往既有 schema 里加东西**
-- （schema.sql / community / auth / admin / security / video 六个文件都动不得）。
-- 本文件由 application.yml 的 schema-locations 末尾追加加载，只建自己的表。
--
-- 设计要点（见 D:\siyige-v2\社区通知-实现方案-v5.md §2）：
--   · 不读状态靠 is_read 布尔字段（决策 I）
--   · 角标靠 Redis Hash notify:unread，**不回源查库**（决策 G）
--   · 点赞类九种里只有 LIKE_POST / LIKE_COMMENT 聚合：agg_key 非空，
--     其余类型 agg_key = null（唯一索引对 NULL 不约束，所以可以有多行）
-- =====================================================================

create table if not exists sy_notification (
  id          bigint generated by default as identity primary key,

  user_id     varchar(32) not null,                     -- 收件人（= sy_user.id）
  module      varchar(16) not null default 'community', -- community | video（以后扩展用）
  type        varchar(20) not null,                     -- COMMENT_POST / REPLY_COMMENT / LIKE_POST /
                                                        -- LIKE_COMMENT / MENTION / POST_DELETED /
                                                        -- COMMENT_DELETED / MUTED / BANNED /
                                                        -- UNMUTED / UNBANNED

  agg_key     varchar(64) null,                         -- 只有点赞类有：LIKE_POST:123
  agg_count   int         not null default 1,           -- 聚合人数（含被显示的那位，决策 D）

  actor_id    varchar(32) null,                         -- 谁干的；聚合时是【最新那个人】
  actor_name  varchar(64) null,                         -- 昵称快照（对方改名前也显示得出来）
  target_id   bigint      null,                         -- 帖子 / 评论 id
  post_id     bigint      null,                         -- 跳转用
  excerpt     varchar(120) null,                        -- 内容快照（被删后还能显示）
  note        varchar(200) null,                        -- 禁言到期 / 删除理由

  is_read     tinyint     not null default 0,           -- 0 未读 / 1 已读
  created_at  timestamp   not null default current_timestamp
);

create index if not exists ix_notify_user on sy_notification(user_id, created_at);

create unique index if not exists ux_notify_agg on sy_notification(user_id, agg_key);
