-- ============================================================================
-- 屏蔽词（W1）：一张表、三个 scope
--
-- 设计：`屏蔽词管理-设计方案.md` §1；SPEC §34
--
-- 为什么三份词表要分 scope 而不是合并成一个「敏感词」：
--   COMMUNITY    社区帖子/评论/标签 -> 打码（标签直接拒）
--   VIDEO_REJECT 视频标题/描述     -> 直接驳回
--   VIDEO_REVIEW 视频标题/描述     -> 转人工复核
-- 同一个词可以同时出现在三个 scope 里（「赌博」既要在社区打码、又要在视频驳回），这是有意的。
--
-- 热点路径（每条内容都要过一遍）不查这张表：WordService 把 enabled=1 的词缓存在内存里，
-- 写操作后重建缓存并让 SensitiveWordMasker 原子换表。
-- ============================================================================

create table if not exists sy_sensitive_word (
  id         bigint generated by default as identity primary key,
  word       varchar(64) not null,           -- 展示原样（保留用户输入的样子）
  word_key   varchar(64) not null,           -- 归一化键：trim + 英文小写；唯一性靠它
  scope      varchar(16) not null,           -- COMMUNITY / VIDEO_REJECT / VIDEO_REVIEW
  enabled    tinyint     not null default 1, -- 0 = 停用（不参与匹配，但记录留着）
  created_by varchar(64),
  created_at timestamp   not null default current_timestamp,
  updated_at timestamp   not null default current_timestamp
);

-- 同一个 scope 里同一个词只有一条（重复导入幂等跳过，靠它兜）
create unique index if not exists ux_word_scope_key on sy_sensitive_word(scope, word_key);
-- 列表/缓存重建都是「按 scope 取 enabled 的那批」
create index if not exists ix_word_scope on sy_sensitive_word(scope, enabled);
