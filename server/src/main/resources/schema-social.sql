-- =====================================================================
-- 好友 / 私聊 / 邀请组队（2026-11-07 新增，V1）
-- 归属：com/siyige/social/*（SocialRepo / FriendService / ChatService）
--
-- 为什么单开一个文件：协作规范 §6 规定**不许往既有 schema 里加东西**。
-- 本文件由 application.yml 的 schema-locations 末尾追加加载（排在 schema-ai.sql 之后）。
--
-- 设计要点（见 D:\siyige-v2\好友系统-实现方案-v2.md §5.1）：
--   · 好友关系存**一行**：user_a < user_b（字典序），保证 (A,B) 与 (B,A) 只有一行，
--     删除时也只可能删掉这一行 —— 存两行最容易只删一边。
--   · 未读不存计数，只存「读到哪条消息 id」（read_a / read_b），多端登录天然一致；
--     侧栏角标另外走 Redis（social:unread:{userId}），两者分工见 SPEC 第 23 节。
--   · 消息表先留 type / payload 两列：本期只有 TEXT，V4 用 INVITE。
--   · 自增 id 同时承担三件事：排序（同毫秒不发乱）、游标分页（beforeId / afterId）、未读比较（id > 已读位置）。
-- =====================================================================

-- 1) 好友关系：字典序一行
create table if not exists sy_friend (
  user_a     varchar(32) not null,
  user_b     varchar(32) not null,
  created_at timestamp   not null default current_timestamp,
  primary key (user_a, user_b)
);
create index if not exists ix_friend_b on sy_friend(user_b);

-- 2) 好友请求：整个生命周期只留痕，PENDING 才参与业务判断
create table if not exists sy_friend_request (
  id         bigint generated by default as identity primary key,
  from_id    varchar(32)  not null,
  to_id      varchar(32)  not null,
  note       varchar(100) null,
  status     varchar(12)  not null default 'PENDING',
  created_at timestamp    not null default current_timestamp,
  handled_at timestamp    null
);
create index if not exists ix_freq_to   on sy_friend_request(to_id, status, created_at);
create index if not exists ix_freq_from on sy_friend_request(from_id, to_id, status);

-- 3) 会话：一对人一行，存排序用的 last_msg_id 与双方已读位置
create table if not exists sy_conversation (
  id          bigint generated by default as identity primary key,
  user_a      varchar(32) not null,
  user_b      varchar(32) not null,
  last_msg_id bigint      null,
  last_msg_at timestamp   null,
  read_a      bigint      not null default 0,
  read_b      bigint      not null default 0,
  created_at  timestamp   not null default current_timestamp,
  constraint ux_conv_pair unique (user_a, user_b)
);
create index if not exists ix_conv_last on sy_conversation(last_msg_id);

-- 4) 消息：一行一条，聊天记录就是「conv_id 相同的所有行按 id 排序」
create table if not exists sy_direct_message (
  id         bigint generated by default as identity primary key,
  conv_id    bigint        not null,
  from_id    varchar(32)   not null,
  to_id      varchar(32)   not null,
  type       varchar(12)   not null default 'TEXT',
  body       varchar(2000) not null,
  payload    varchar(500)  null,
  created_at timestamp     not null default current_timestamp
);
create index if not exists ix_dm_conv on sy_direct_message(conv_id, id);
