-- ============================================================================
-- 帖子标签（T1）：两张新表
--
-- 设计：`帖子标签系统-设计方案.md` §1；SPEC §29
--
-- 为什么单独一个文件：既有 schema（schema.sql / schema-community.sql / …）一律不动，
-- 新表只进这里；application.yml 的 schema-locations 把它排在 schema-community.sql 之后
-- （语义上它引用 sy_post.id，但不建外键 —— 与项目其它表一致，删帖走软删）。
-- ============================================================================

-- 标签本体
--   name     展示名（保留用户输入的样子：大小写/空格归一后）
--   name_key 归一化键（小写 + 去首尾空格 + 连续空格合一），唯一约束打在这列 ——
--            否则 `AI` / `ai` / `Ai ` 会变成三个标签
--   scope    预留：目前只有 POST（以后要做「辩题标签」不用改表）
--   use_count 冗余计数：热门排序与后台列表用。**不做 +1/-1**，变动后按 tag_id 重算
--            （增量有四个入口，漏一个就永久漂移；重算走 ix_post_tag_tag，千级数据微秒级）
--   created_by 管理员账号 或 用户 id（种子/后台预置为管理员账号）
create table if not exists sy_tag (
  id         bigint generated by default as identity primary key,
  name       varchar(24) not null,
  name_key   varchar(24) not null,
  scope      varchar(16) not null default 'POST',
  use_count  int         not null default 0,
  created_by varchar(64),
  created_at timestamp   not null default current_timestamp
);

create unique index if not exists ux_tag_scope_key on sy_tag(scope, name_key);

-- 帖子-标签关联
--   不建外键：删标签时由 TagRepo 在同一事务里先断关联再删标签（设计 §1）；
--   帖子软删（sy_post.status=2）**不动**这里 —— 恢复后标签必须还在（红线 4）
create table if not exists sy_post_tag (
  post_id    bigint    not null,
  tag_id     bigint    not null,
  created_at timestamp not null default current_timestamp,
  primary key (post_id, tag_id)
);

-- 反向索引：按标签筛帖子（列表页 `exists (select 1 from sy_post_tag …)`）与重算 use_count 都走它
create index if not exists ix_post_tag_tag on sy_post_tag(tag_id, post_id);
