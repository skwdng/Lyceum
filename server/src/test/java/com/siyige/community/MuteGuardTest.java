package com.siyige.community;

import com.siyige.auth.AuthException;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import java.sql.Timestamp;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.Map;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

/**
 * A3：社区禁言校验（用真 H2 + 真 SQL，不 mock JdbcTemplate——
 * 这里最容易写错的就是 `until > now` 这个条件，必须让真 SQL 跑一遍）。
 */
class MuteGuardTest {

    private JdbcTemplate jdbc;
    private MuteGuard guard;

    @BeforeEach
    void setUp() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:mute" + UUID.randomUUID().toString().replace("-", "") + ";DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        ds.setPassword("");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("""
                create table sy_community_ban (
                  id         bigint generated by default as identity primary key,
                  user_id    varchar(32)  not null,
                  banned_by  bigint       not null,
                  reason     varchar(200) null,
                  until      timestamp    not null,
                  report_id  bigint       null,
                  created_at timestamp    not null default current_timestamp
                )
                """);
        guard = new MuteGuard(jdbc);
    }

    private void ban(String userId, Instant until, String reason) {
        jdbc.update("insert into sy_community_ban(user_id, banned_by, reason, until) values(?, ?, ?, ?)",
                userId, 1L, reason, Timestamp.from(until));
    }

    @Test
    void 没被禁言时放行且banInfo为false() {
        assertDoesNotThrow(() -> guard.assertNotMuted("zhang"));

        Map<String, Object> info = guard.banInfo("zhang");
        assertEquals(false, info.get("banned"));
        assertNull(info.get("until"));
        assertNull(info.get("reason"));
    }

    @Test
    void 生效中的禁言抛403_MUTED且带到期时间() {
        Instant until = Instant.now().plus(3, ChronoUnit.DAYS);
        ban("zhang", until, "人身攻击");

        AuthException e = assertThrows(AuthException.class, () -> guard.assertNotMuted("zhang"));

        assertEquals("MUTED", e.code());
        assertEquals(403, e.status().value());
        assertTrue(e.getMessage().contains("你已被禁言至"), e.getMessage());
        // yyyy-MM-dd HH:mm 格式，前端直接展示
        assertTrue(e.getMessage().matches(".*\\d{4}-\\d{2}-\\d{2} \\d{2}:\\d{2}.*"), e.getMessage());
    }

    @Test
    void 已过期的禁言不拦人() {
        ban("zhang", Instant.now().minus(1, ChronoUnit.HOURS), "旧禁言");

        assertDoesNotThrow(() -> guard.assertNotMuted("zhang"));
        assertEquals(false, guard.banInfo("zhang").get("banned"));
    }

    @Test
    void 禁言确实带出了原因与到期毫秒() {
        Instant until = Instant.now().plus(7, ChronoUnit.DAYS);
        ban("zhang", until, "垃圾广告");

        Map<String, Object> info = guard.banInfo("zhang");
        assertEquals(true, info.get("banned"));
        assertEquals("垃圾广告", info.get("reason"));
        // until 下发给前端统一用 epoch 毫秒
        long ms = ((Number) info.get("until")).longValue();
        assertTrue(Math.abs(ms - until.toEpochMilli()) < 2000, "到期时间对不上：" + ms);
    }

    @Test
    void 多条禁言时取最晚那条() {
        ban("zhang", Instant.now().plus(1, ChronoUnit.DAYS), "第一次");
        Instant latest = Instant.now().plus(5, ChronoUnit.DAYS);
        ban("zhang", latest, "第二次");

        long ms = ((Number) guard.banInfo("zhang").get("until")).longValue();
        assertTrue(Math.abs(ms - latest.toEpochMilli()) < 2000, "应取最晚到期，实际：" + ms);
        assertEquals("第二次", guard.banInfo("zhang").get("reason"));
    }

    @Test
    void 别人的禁言不影响自己() {
        ban("lisi", Instant.now().plus(1, ChronoUnit.DAYS), "x");

        assertDoesNotThrow(() -> guard.assertNotMuted("zhang"));
        assertThrows(AuthException.class, () -> guard.assertNotMuted("lisi"));
    }

    @Test
    void 空userId不炸也不拦() {
        assertDoesNotThrow(() -> guard.assertNotMuted(null));
        assertDoesNotThrow(() -> guard.assertNotMuted("  "));
    }
}
