package com.siyige.admin;

import com.siyige.auth.AuthException;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import java.sql.Timestamp;
import java.time.Duration;
import java.time.Instant;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

/**
 * A3：禁言写入（管理端）。
 *
 * <p>用真 H2 + 真 SQL，重点验方案 R2 那条"多次禁言取最晚到期、不累加天数"。
 */
class BanServiceTest {

    private JdbcTemplate jdbc;
    private BanRepo repo;
    private BanService service;

    @BeforeEach
    void setUp() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:ban" + UUID.randomUUID().toString().replace("-", "") + ";DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        ds.setPassword("");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("""
                create table sy_community_ban (
                  id         bigint generated by default as identity primary key,
                  user_id    varchar(32)  not null,
                  banned_by  bigint       not null,
                  reason     varchar(200) null,
                  until      timestamp    not null,
                  report_id  bigint       null,
                  created_at timestamp    not null default current_timestamp
                )
                """);
        repo = new BanRepo(jdbc);
        service = new BanService(repo);
    }

    private long count() {
        Long n = jdbc.queryForObject("select count(*) from sy_community_ban", Long.class);
        return n == null ? 0 : n;
    }

    @Test
    void 禁言一天写入一行且到期时间约一天后() {
        Timestamp until = service.ban("zhang", 1, "人身攻击", 1L);

        assertEquals(1, count());
        long deltaMin = Duration.between(Instant.now(), until.toInstant()).toMinutes();
        assertTrue(Math.abs(deltaMin - 24 * 60) < 5, "到期时间应约 24 小时后，实际差 " + deltaMin + " 分钟");
    }

    @Test
    void 天数只接受1_3_7() {
        for (int bad : new int[]{0, 2, 5, 30, -1}) {
            AuthException e = assertThrows(AuthException.class, () -> service.ban("zhang", bad, null, 1L),
                    "应拒绝 days=" + bad);
            assertEquals("INVALID_PARAM", e.code());
        }
        assertEquals(0, count(), "非法天数不该写库");
    }

    @Test
    void 重复禁言取最晚到期_不累加天数() {
        Timestamp first = service.ban("zhang", 3, "第一次", 1L);
        Timestamp second = service.ban("zhang", 7, "第二次", 1L);

        // 基准是第一次的到期时间，再加 7 天 —— 而不是「3+7=10 天从今天算」
        long expectMin = Duration.between(Instant.now(), first.toInstant()).toMinutes() + 7 * 24 * 60;
        long actualMin = Duration.between(Instant.now(), second.toInstant()).toMinutes();
        assertTrue(Math.abs(actualMin - expectMin) < 5,
                "叠加规则应为「第一次到期 + 7 天」，期望约 " + expectMin + " 分钟，实际 " + actualMin);

        assertEquals(2, count(), "两次禁言各记一行（保留历史）");
        assertEquals(second, repo.latestActiveUntil("zhang"), "生效到期取最晚那条");
    }

    @Test
    void 解禁后不再生效但历史保留() {
        service.ban("zhang", 7, "垃圾广告", 1L);
        assertEquals(1, repo.countActiveUsers());

        service.unban("zhang");

        assertNull(repo.latestActiveUntil("zhang"), "解禁后不应再有生效禁言");
        assertEquals(0, repo.countActiveUsers());
        assertEquals(1, count(), "历史行要保留，不删表");
    }

    @Test
    void 解禁只影响该用户() {
        service.ban("zhang", 7, null, 1L);
        service.ban("lisi", 7, null, 1L);

        service.unban("zhang");

        assertNull(repo.latestActiveUntil("zhang"));
        assertNotNull(repo.latestActiveUntil("lisi"));
        assertEquals(1, repo.countActiveUsers());
    }

    @Test
    void 禁言原因超长要拒绝() {
        AuthException e = assertThrows(AuthException.class,
                () -> service.ban("zhang", 1, "字".repeat(201), 1L));
        assertEquals("INVALID_PARAM", e.code());
    }

    @Test
    void bannedBy记录操作人() {
        service.ban("zhang", 1, null, 88L);

        Long by = jdbc.queryForObject("select banned_by from sy_community_ban", Long.class);
        assertEquals(88L, by);
    }
}
