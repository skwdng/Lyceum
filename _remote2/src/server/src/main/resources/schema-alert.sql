-- 管理台告警（A1）：两张表
--
-- 设计：`管理台告警-设计方案.md` §1；SPEC §30
--
-- 为什么单独一个文件：既有 schema 一律不动，新表只进这里；
-- application.yml 的 schema-locations 把它排在最后（它不引用别的表，只读 sy_report / sy_daily_active）。
-- ============================================================================

-- 告警本体
--   rule_key    USER_REPORT_BURST / POST_REPORT_BURST / REPORT_BACKLOG / DAU_MISSING
--   target_type USER / POST / COMMENT / null（全局类规则没有对象）
--   target_id   用户 id / 帖子 id / 评论 id；全局类为 null（**字符串**，因为以后可能放 topic t7 这类 id）
--   level       WARN / CRIT
--   metric      触发时的实际值（34 = 24 小时内被举报 34 次）
--   dedup_key   唯一指纹：规则 + 对象 + 日期。**去重的全部秘密都在这列**
--               （`USER_REPORT_BURST:u_1029:2026-11-16`），唯一索引兜住并发插入
--   status      OPEN / ACKED / RESOLVED
--   acked_*     人点「已处理」的留痕（**不写 sy_audit_log**，处理记录页只放内容处置动作）
--   first_seen  第一次触发时间（去重命中时不改）
--   last_seen   最近一次触发时间（每次扫描 touch）
create table if not exists sy_alert (
  id          bigint generated by default as identity primary key,
  rule_key    varchar(40)  not null,
  target_type varchar(8),
  target_id   varchar(32),
  level       varchar(8)   not null,
  title       varchar(120) not null,
  detail      varchar(500),
  metric      bigint,
  dedup_key   varchar(96)  not null,
  status      varchar(12)  not null default 'OPEN',
  acked_by    varchar(64),
  acked_note  varchar(200),
  acked_at    timestamp,
  resolved_at timestamp,
  first_seen  timestamp    not null default current_timestamp,
  last_seen   timestamp    not null default current_timestamp
);

-- 一个对象一天只报一次
create unique index if not exists ux_alert_dedup on sy_alert(dedup_key);
-- 红点与默认列表：status + last_seen
create index if not exists ix_alert_open   on sy_alert(status, last_seen);
-- 同一对象的历史（去重命中时按这三个 + status 找 OPEN）
create index if not exists ix_alert_target on sy_alert(rule_key, target_type, target_id, status);

-- 规则静音：静音期间**不再生成新告警**，已存在的照常显示（用于「已知问题，正在修，别吵我」）
create table if not exists sy_alert_mute (
  rule_key    varchar(40) primary key,
  muted_until timestamp   not null,
  muted_by    varchar(64),
  created_at  timestamp   not null default current_timestamp
);
